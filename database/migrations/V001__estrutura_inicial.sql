-- -----------------------------------------------------------------------------
-- Modelo inspirado nos campos de curso do Moodle (fullname, shortname, summary,
-- category, startdate), acrescido de modalidade, status, módulos e aulas.
-- Script idempotente para a estrutura: pode ser executado pela API (migrador
-- automático), pelo docker-compose ou manualmente no SQL Editor do Supabase.
-- =============================================================================

-- Normaliza texto para busca: minúsculas e sem acentos.
-- Usa apenas translate()/lower() (funções nativas e IMMUTABLE), evitando a
-- dependência da extensão "unaccent", que nem sempre está disponível/habilitada.
CREATE OR REPLACE FUNCTION f_normalizar(texto text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
RETURNS NULL ON NULL INPUT
AS $$
    SELECT lower(translate(
        texto,
        'áàâãäåÁÀÂÃÄÅéèêëÉÈÊËíìîïÍÌÎÏóòôõöÓÒÔÕÖúùûüÚÙÛÜçÇñÑ',
        'aaaaaaAAAAAAeeeeEEEEiiiiIIIIoooooOOOOOuuuuUUUUcCnN'
    ));
$$;

CREATE TABLE IF NOT EXISTS categoria (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(80)  NOT NULL,
    slug        varchar(80)  NOT NULL UNIQUE,
    icone       varchar(120) NOT NULL,
    descricao   varchar(300)
);

CREATE TABLE IF NOT EXISTS modalidade (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(80)  NOT NULL,
    slug        varchar(80)  NOT NULL UNIQUE,
    descricao   varchar(300)
);

CREATE TABLE IF NOT EXISTS status_curso (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(80)  NOT NULL,
    slug        varchar(80)  NOT NULL UNIQUE,
    ordem       smallint     NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS curso (
    id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo          varchar(200) NOT NULL,              -- Moodle: fullname
    nome_breve             varchar(60)  NOT NULL UNIQUE,       -- Moodle: shortname
    resumo                 varchar(400) NOT NULL,              -- texto curto do card
    descricao              text         NOT NULL,              -- Moodle: summary
    categoria_id           integer      NOT NULL REFERENCES categoria (id),
    modalidade_id          integer      NOT NULL REFERENCES modalidade (id),
    status_id              integer      NOT NULL REFERENCES status_curso (id),
    carga_horaria          smallint     NOT NULL CHECK (carga_horaria > 0),
    publico_alvo           varchar(300) NOT NULL,
    imagem_url             varchar(300) NOT NULL,
    imagem_descricao       varchar(300) NOT NULL,              -- texto alternativo (acessibilidade)
    data_disponibilizacao  date,                               -- Moodle: startdate (quando aplicável)
    destaque               boolean      NOT NULL DEFAULT false,
    criado_em              timestamptz  NOT NULL DEFAULT now(),
    -- Coluna de busca gerada: nome completo + nome breve normalizados.
    nome_busca             text GENERATED ALWAYS AS (f_normalizar(nome_completo || ' ' || nome_breve)) STORED
);

CREATE INDEX IF NOT EXISTS ix_curso_categoria  ON curso (categoria_id);
CREATE INDEX IF NOT EXISTS ix_curso_modalidade ON curso (modalidade_id);
CREATE INDEX IF NOT EXISTS ix_curso_status     ON curso (status_id);

CREATE TABLE IF NOT EXISTS modulo (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id       integer      NOT NULL REFERENCES curso (id) ON DELETE CASCADE,
    ordem          smallint     NOT NULL,
    titulo         varchar(200) NOT NULL,
    descricao      varchar(600) NOT NULL,
    carga_horaria  smallint     NOT NULL CHECK (carga_horaria > 0),
    UNIQUE (curso_id, ordem)
);

CREATE TABLE IF NOT EXISTS aula (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id        integer      NOT NULL REFERENCES modulo (id) ON DELETE CASCADE,
    ordem            smallint     NOT NULL,
    titulo           varchar(200) NOT NULL,
    descricao        text         NOT NULL,              -- conteúdo exibido na tela de aula (AVA)
    duracao_minutos  smallint     NOT NULL CHECK (duracao_minutos > 0),
    UNIQUE (modulo_id, ordem)
);
